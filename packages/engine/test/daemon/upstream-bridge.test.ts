  it("refuses one whose event recorded no SHA-256", async () => {
    const dir = root();
    writeFileSync(join(dir, ".vtc/lookback/replays/p-engineer-1.json"), JSON.stringify(REPLAY));
    expect(await read(dir, undefined)).toMatch(/no recorded SHA-256/);
  });
