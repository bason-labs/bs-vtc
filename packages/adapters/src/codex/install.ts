/**
 * Codex `install` (§4.4, §12.1, AD-6 rule 5, AD-16 rules 3–4). Places what the compiler emitted,
 * authoring nothing:
 * 1. copies the compiled agent files (`agents/vtc-*.toml`, listed in `vtc-manifest.json`) into
 *    `.codex/agents/` (the repo's for the project scope, `<codexHome>/agents/` for the user
 *    scope) and removes VTC agent files a newer plugin no longer lists;
 * 2. writes the engine entry `[mcp_servers.vtc]` = `engineMcpServer("codex")` into that scope's
 *    `config.toml`, replacing only that table and keeping everything else byte for byte;
 * 3. places the plugin's skills (the Lead loop, the `vtc` command, the packs and lenses) where
 *    Codex loads skills (learn.chatgpt.com/docs/build-skills: `$REPO_ROOT/.agents/skills` for the
 *    project scope, `$HOME/.agents/skills` for the user scope), each as `vtc-<name>/` with a
 *    `.vtc-generated` marker, and removes marked `vtc-*` skills a newer plugin no longer has.
 * 4. registers the plugin with Codex (D-bn, spine §5 readings 168 and 213): a local marketplace
 *    under the VTC home, `codex plugin marketplace add` and `codex plugin add`
 *    (`plugin-registration.ts`), which makes its hooks active in the Codex desktop app once the
 *    user trusts them. Registration goes to the user's Codex home whatever the scope (Codex keeps
 *    marketplaces and plugins per user).
 * The Codex home is resolved once (`CodexInstallDeps.codexHome`) and is both where the user-scope
 * agents and `config.toml` go and where the plugin is registered, so one install never splits
 * across two Codex homes. It comes from injected input only, never the ambient environment: the
 * cli's `codexHome` (its `$CODEX_HOME`), else `<InstallRequest.home>/.codex` (AD-6 rule 5). The skills stay placed as in step 3 too: whether a Codex
 *    CLI session loads a registered plugin's skills is not yet checked, and the placed copies are
 *    the path shown to work.
 * The notes also say how a Codex Lead's roles run (human decision H-1, spine §5 reading 99, which
 * replaces the earlier "no roles in v1"): the engine starts them itself as headless Codex runs,
 * sandboxed and budget-checked; in-session Codex roles stay refused (reading 82), and where a
 * headless launch is impossible `vtc doctor` or a Claude Lead is the remedy.
 */
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import { engineMcpServer, type InstallRequest, type InstallResult } from "@vtc/shared";
import { filesUnder, readTextOrNull, replaceDirectory, writeFileAtomic } from "../common/files.js";
import { insidePlugin, readPluginManifest } from "../common/plugin.js";
import {
  CODEX_MARKETPLACE,
  codexMarketplaceDir,
  registerCodexPlugin,
  writeCodexMarketplace,
  type RunCommand,
} from "./plugin-registration.js";

/** The first line the compiler writes into every Codex agent file. */
const GENERATED_MARK = "# Generated by @vtc/compiler";
const MANAGED_MARK = "# Managed by `vtc install`: the vtc engine bridge (rewritten on install).";
/** The file that marks a skill directory `vtc install` placed (and may replace or remove). */
const SKILL_MARK = ".vtc-generated";

const tomlString = (value: string): string => JSON.stringify(value);

/** The `[mcp_servers.<name>]` table for the engine bridge. */
export const codexMcpServerTable = (): string => {
  const entry = engineMcpServer("codex");
  return [
    MANAGED_MARK,
    `[mcp_servers.${entry.name}]`,
    `command = ${tomlString(entry.command)}`,
    `args = [${entry.args.map(tomlString).join(", ")}]`,
    "",
  ].join("\n");
};

/** A table header's dotted name without quotes or spaces, or null for a non-header line. */
const headerName = (line: string): string | null => {
  const match = /^\s*\[\[?([^\]]+)\]\]?\s*(#.*)?$/.exec(line);
  return match?.[1] === undefined ? null : match[1].replace(/["'\s]/g, "");
};

/**
 * The multi-line string delimiter (`"""` or `'''`) still open after `line`, given the one open
 * before it (null = none). Approximate (escaped quotes are not tracked), which is enough to keep
 * a header-like line inside a string from being read as a table.
 */
const openStringAfter = (line: string, open: string | null): string | null => {
  let current = open;
  let index = 0;
  for (;;) {
    if (current === null) {
      const basic = line.indexOf('"""', index);
      const literal = line.indexOf("'''", index);
      if (basic < 0 && literal < 0) return null;
      const at = basic < 0 ? literal : literal < 0 ? basic : Math.min(basic, literal);
      current = at === basic ? '"""' : "'''";
      index = at + 3;
    } else {
      const at = line.indexOf(current, index);
      if (at < 0) return current;
      current = null;
      index = at + 3;
    }
  }
};

/**
 * `config` with the `[mcp_servers.<name>]` table (and its sub-tables) replaced by `table`.
 * Refuses a config that defines the server some other way (inline, as dotted keys, or inside an
 * inline `mcp_servers = {...}`), since rewriting that safely needs a full TOML parser.
 */
export const upsertMcpServerTable = (config: string, name: string, table: string): string => {
  const own = `mcp_servers.${name}`;
  const lines = config.split("\n");
  const kept: string[] = [];
  let current: string | null = null;
  let skipping = false;
  let openString: string | null = null;
  for (const line of lines) {
    const inString = openString !== null;
    openString = openStringAfter(line, openString);
    const header = inString ? null : headerName(line);
    if (header !== null) {
      current = header;
      skipping = header === own || header.startsWith(`${own}.`);
      if (skipping && kept.at(-1) === MANAGED_MARK) kept.pop();
    } else if (!skipping && !inString) {
      const key = /^\s*([A-Za-z0-9_."'-]+)\s*=/.exec(line)?.[1]?.replace(/["'\s]/g, "");
      const fullKey = key === undefined ? null : current === null ? key : `${current}.${key}`;
      if (
        fullKey !== null &&
        (fullKey === own || fullKey.startsWith(`${own}.`) || own.startsWith(`${fullKey}.`))
      ) {
        throw new Error(
          `config.toml defines ${own} outside a [${own}] table; remove it, then install again`,
        );
      }
    }
    if (!skipping) kept.push(line);
  }
  const body = kept.join("\n").replace(/\n+$/, "");
  return body === "" ? table : `${body}\n\n${table}`;
};

const isGeneratedAgent = (path: string): boolean => {
  try {
    return readFileSync(path, "utf8").startsWith(GENERATED_MARK);
  } catch {
    return false;
  }
};

/** Steps 1–3, synchronous: the files in the repo or the user's home. */
const placeCodexFiles = (
  request: InstallRequest,
  codexHome: string,
): InstallResult & { readonly plugin: string } => {
  const manifest = readPluginManifest(request.pluginDir, "codex");
  const codexDir = request.scope === "user" ? codexHome : join(request.projectRoot, ".codex");
  const agentsDir = join(codexDir, "agents");
  const written: string[] = [];

  const placed = new Set<string>();
  for (const agent of manifest.agents) {
    const name = basename(agent.file);
    const target = join(agentsDir, name);
    writeFileAtomic(target, readFileSync(insidePlugin(request.pluginDir, agent.file), "utf8"));
    placed.add(name);
    written.push(target);
  }
  const removed: string[] = [];
  if (existsSync(agentsDir)) {
    for (const name of readdirSync(agentsDir)) {
      const path = join(agentsDir, name);
      if (!name.startsWith("vtc-") || !name.endsWith(".toml") || placed.has(name)) continue;
      if (!isGeneratedAgent(path)) continue;
      rmSync(path, { force: true });
      removed.push(name);
    }
  }

  const skillsDir = join(
    request.scope === "user" ? request.home : request.projectRoot,
    ".agents",
    "skills",
  );
  const skillDirs = new Set<string>();
  for (const skill of manifest.skills) {
    const dir = `vtc-${skill.name}`;
    const target = join(skillsDir, dir);
    replaceDirectory(insidePlugin(request.pluginDir, dirname(skill.file)), target);
    writeFileSync(join(target, SKILL_MARK), "");
    skillDirs.add(dir);
    written.push(join(target, "SKILL.md"));
  }
  if (existsSync(skillsDir)) {
    for (const name of readdirSync(skillsDir)) {
      if (!name.startsWith("vtc-") || skillDirs.has(name)) continue;
      if (!existsSync(join(skillsDir, name, SKILL_MARK))) continue;
      rmSync(join(skillsDir, name), { recursive: true, force: true });
      removed.push(name);
    }
  }

  const configPath = join(codexDir, "config.toml");
  const entry = engineMcpServer("codex");
  writeFileAtomic(
    configPath,
    upsertMcpServerTable(readTextOrNull(configPath) ?? "", entry.name, codexMcpServerTable()),
  );
  written.push(configPath);

  return {
    plugin: manifest.plugin,
    written,
    notes: [
      ...(request.scope === "project"
        ? ["Codex reads the repo's .codex/ only once you trust this project in Codex."]
        : []),
      ...(removed.length === 0
        ? []
        : [`Removed agent files the current plugin no longer has: ${removed.join(", ")}.`]),
      `Placed the vtc skills in ${skillsDir} (the Lead loop is the vtc-lead skill).`,
      "A Codex Lead's roles run as headless Codex runs the engine starts itself (codex exec, sandboxed with the network off, budget-checked, no approval prompts, and only their own engine tools on the vtc bridge: never approve, answer or change_request), never inside the Codex session (VTC cannot confirm that session keeps the network off). Where a headless Codex run cannot start (Codex not logged in, or a platform whose network-off sandbox is not yet shown to block the engine's socket), the task parks blocked: run vtc doctor, or run the Lead in Claude Code instead (vtc install --host claude-code).",
    ],
  };
};

/**
 * The `version` of the compiled plugin's `plugin.json`: the vtc release version (the compiler
 * requires one, and the cli checks it equals its `VERSION`). `null` when it cannot be read.
 */
const shippedVersion = (pluginDir: string): string | null => {
  try {
    const parsed = JSON.parse(readFileSync(insidePlugin(pluginDir, "plugin.json"), "utf8")) as {
      version?: unknown;
    } | null;
    return typeof parsed?.version === "string" ? parsed.version : null;
  } catch {
    return null;
  }
};

export interface CodexInstallDeps {
  /** Runs `codex plugin …` (a short command whose output is read; tests pass a fake). */
  readonly run: RunCommand;
  /**
   * The user's Codex home: where the user-scope agents and `config.toml` go and where the plugin
   * is registered (the cli's `$CODEX_HOME`, else `<InstallRequest.home>/.codex`).
   */
  readonly codexHome: string;
}

/**
 * The whole install: the files (steps 1–3), then the plugin registration (step 4). A failed
 * registration rejects, naming what was already placed, so `vtc install codex` never reports a
 * plugin Codex does not have.
 */
export const installCodex = async (
  request: InstallRequest,
  deps: CodexInstallDeps,
): Promise<InstallResult> => {
  const { plugin, written, notes } = placeCodexFiles(request, deps.codexHome);
  const root = codexMarketplaceDir(request.vtcHome ?? join(request.home, ".vtc"));
  const index = writeCodexMarketplace(request.pluginDir, root, plugin);
  let registered;
  try {
    registered = await registerCodexPlugin(deps.run, { root, codexHome: deps.codexHome, plugin });
  } catch (error) {
    const reason = error instanceof Error ? error.message : String(error);
    throw new Error(
      `placed the vtc agents, skills and engine entry, but registering the ${plugin} plugin with Codex failed: ${reason}. Fix that, then run vtc install codex again.`,
      { cause: error },
    );
  }
  const shipped = shippedVersion(request.pluginDir);
  const version = registered.version ?? shipped;
  const stale =
    registered.version !== null && shipped !== null && registered.version !== shipped
      ? ` Codex reports version ${registered.version}, but this vtc ships ${shipped}: run vtc install codex again after restarting Codex.`
      : "";
  return {
    written: [...written, ...filesUnder(join(root, plugin)), index],
    notes: [
      ...notes,
      ...(registered.replacedSource === null
        ? []
        : [
            `Replaced the ${CODEX_MARKETPLACE} marketplace an earlier VTC home registered (${registered.replacedSource}).`,
          ]),
      `Registered the ${plugin} plugin with Codex as ${registered.pluginId} from the ${CODEX_MARKETPLACE} marketplace in ${root}${version === null ? "" : ` (version ${version})`}, for your Codex user (${deps.codexHome}; Codex keeps its copy in ${registered.installedPath}). Its hooks run in the Codex desktop app once you trust them there; the engine's headless role runs never load it.${stale}`,
    ],
  };
};
