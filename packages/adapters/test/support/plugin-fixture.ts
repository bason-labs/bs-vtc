/**
 * A small compiled plugin in the compiler's output layout (`dist/<host>-plugin`, AD-16), built
 * from the shared contracts so its manifest always validates. Synthetic: two agents, one skill.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import {
  agentNameFor,
  CONTRACTS_VERSION,
  engineMcpServer,
  PLUGIN_MANIFEST_ASSET,
  PluginManifestSchema,
  promptShaFor,
  type HostId,
  type PluginManifestInput,
} from "@vtc/shared";

interface FixtureAgent {
  readonly role: string;
  readonly mode: string | null;
  readonly sandbox: "read-only" | "workspace-write";
}

export const FIXTURE_AGENTS: readonly FixtureAgent[] = [
  { role: "qa", mode: "judge", sandbox: "read-only" },
  { role: "engineer", mode: null, sandbox: "workspace-write" },
];

const instructionsFor = (agent: FixtureAgent): string =>
  `# ${agent.role}\n\nFixture instructions for ${agent.role}${agent.mode === null ? "" : ` (${agent.mode})`}.\n`;

const write = (root: string, path: string, text: string): void => {
  const full = join(root, path);
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, text, "utf8");
};

export const writeFixturePlugin = (
  host: HostId,
  root: string,
  agents: readonly FixtureAgent[] = FIXTURE_AGENTS,
): PluginManifestInput => {
  const ext = host === "codex" ? "toml" : "md";
  const mcp = engineMcpServer(host);
  write(
    root,
    ".mcp.json",
    `${JSON.stringify({ mcpServers: { vtc: { command: mcp.command, args: mcp.args } } }, null, 2)}\n`,
  );
  write(
    root,
    host === "codex" ? "plugin.json" : ".claude-plugin/plugin.json",
    `${JSON.stringify({ name: "vtc", version: "0.1.0", description: "VTC fixture plugin." }, null, 2)}\n`,
  );
  write(root, "skills/vtc/SKILL.md", "---\nname: vtc\ndescription: Fixture.\n---\n\nFixture.\n");
  const manifestAgents = agents.map((agent) => {
    const name = agentNameFor(agent.role, agent.mode ?? undefined);
    const instructions = instructionsFor(agent);
    const file = `agents/${name}.${ext}`;
    write(
      root,
      file,
      host === "codex"
        ? [
            `# Generated by @vtc/compiler from roles/${agent.role} v1.0.0. Do not edit.`,
            `name = "${name}"`,
            `description = "Fixture agent."`,
            `model_reasoning_effort = "medium"`,
            `sandbox_mode = "${agent.sandbox}"`,
            `developer_instructions = """\n${instructions}"""`,
            "",
          ].join("\n")
        : `---\nname: ${name}\ndescription: Fixture agent.\ntools: Read, Grep, Glob\nmodel: sonnet\n---\n${instructions}`,
    );
    return {
      name,
      role: agent.role,
      mode: agent.mode,
      kind: "core" as const,
      discipline: null,
      role_version: "1.0.0",
      file,
      prompt_sha256: promptShaFor(instructions),
      tier: "mid" as const,
      effort: "medium" as const,
    };
  });
  const manifest: PluginManifestInput = {
    v: 1,
    host,
    plugin: "vtc",
    contracts_version: CONTRACTS_VERSION,
    agents: manifestAgents,
    skills: [{ name: "vtc", kind: "command", pack: null, file: "skills/vtc/SKILL.md" }],
  };
  PluginManifestSchema.parse(manifest);
  write(root, PLUGIN_MANIFEST_ASSET, `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
};
