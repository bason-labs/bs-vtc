/**
 * Plugin hook wiring (AD-8 rule 3, AD-16 rule 1; spine §5 reading 31). Every hook runs only the
 * frozen `vtc hook <event> --host <host>` command (`vtcHookCommand` in @vtc/shared), which fails
 * open and blocks only a VTC role agent's git or out-of-scope write: an extra layer of defence,
 * never the enforcement point (the engine checks every write and every submit). The wiring is
 * generated, never hand-written, so it cannot drift from the contract.
 *
 * Provisional until the spike (spine §7, "Host hook wiring for `vtc hook`"): the host event
 * names, the Codex hook file format and the fields the hosts pass.
 */
import { VTC_HOOK, vtcHookCommand, type HostId, type VtcHookEvent } from "@vtc/shared";

/** Where each plugin carries its hook wiring, relative to the plugin root. */
export const HOOKS_FILE = "hooks/hooks.json";

/** The host's name for each `vtc hook` event (the same on both hosts, provisional). */
export const HOST_HOOK_EVENTS: Readonly<Record<VtcHookEvent, string>> = {
  "session-start": "SessionStart",
  "pre-tool-use": "PreToolUse",
  "subagent-stop": "SubagentStop",
};

/**
 * Tools whose calls the pre-tool-use hook sees, per host: on Claude Code the shell and the
 * file-writing tools (the only calls the command can block); on Codex every call.
 */
const PRE_TOOL_MATCHER: Readonly<Record<HostId, string | undefined>> = {
  "claude-code": "Bash|Write|Edit|MultiEdit|NotebookEdit",
  codex: undefined,
};

/** Hosts take hook timeouts in whole seconds; the contract gives milliseconds. */
export const HOOK_TIMEOUT_SECONDS = Math.ceil(VTC_HOOK.timeoutMs / 1000);

const SHELL_SAFE = /^[A-Za-z0-9._-]+$/;

/** `vtc hook <event> --host <host>` as one command line (every part is shell-safe). */
export const hookCommandLine = (event: VtcHookEvent, host: HostId): string => {
  const { command, args } = vtcHookCommand(event, host);
  const parts = [command, ...args];
  for (const part of parts) {
    if (!SHELL_SAFE.test(part)) throw new Error(`hook command part ${part} needs quoting`);
  }
  return parts.join(" ");
};

/** The plugin's `hooks/hooks.json` for `host`. */
export const renderHooks = (host: HostId): string => {
  const hooks: Record<string, unknown[]> = {};
  for (const [event, hostEvent] of Object.entries(HOST_HOOK_EVENTS) as [VtcHookEvent, string][]) {
    const matcher = event === "pre-tool-use" ? PRE_TOOL_MATCHER[host] : undefined;
    hooks[hostEvent] = [
      {
        ...(matcher === undefined ? {} : { matcher }),
        hooks: [
          {
            type: "command",
            command: hookCommandLine(event, host),
            timeout: HOOK_TIMEOUT_SECONDS,
          },
        ],
      },
    ];
  }
  const description =
    "VTC hooks, generated by @vtc/compiler from the `vtc hook` contract: an extra layer of defence only (spine AD-8 rule 3). The engine enforces; `vtc hook` exits 0 when no VTC run is active.";
  return `${JSON.stringify({ description, hooks }, null, 2)}\n`;
};
